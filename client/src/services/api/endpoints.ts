import { http } from './client';
import type {
  ApiHealth, ApprovalDecision, ApprovalRecord, AuditPage, AuthResponse, ChatSummary, ChatThread, CreatePrInput,
  CreateRepoInput, CreateTaskInput, FileContent, GithubRepo, GraphData, HealthReport, Me, Finding, Repo, SearchResult,
  SecurityReport, SemanticResult, SymbolsResult, ImpactResult, PrReview, CiItem, BudgetStatus, NotifySettings, LlmCheck, BenchResult, BenchStatus, McpServer, McpInput, ActivityItem, RepoIssue, MemoryNote, Stats, Task, TaskDetail, TaskDiff, TaskPage, TaskStatus, TreeFile, Usage,
} from '../../types/index';

const enc = encodeURIComponent;

export const api = {
  register: (input: { email: string; password: string; name: string }) => http.post<AuthResponse>('/api/auth/register', input),
  login: (input: { email: string; password: string }) => http.post<AuthResponse>('/api/auth/login', input),
  authProviders: () => http.get<{ google: boolean; github: boolean }>('/api/auth/providers'),
  githubOAuthUrl: () => http.get<{ url: string }>('/api/github/oauth-url'),
  semanticSearch: (id: string, q: string, mode: string, rerank = false) => http.get<SemanticResult>(`/api/repos/${enc(id)}/semantic-search`, { q, mode, limit: 12, rerank: String(rerank) }),
  symbols: (id: string, path?: string) => http.get<SymbolsResult>(`/api/repos/${enc(id)}/symbols`, { path }),
  impact: (id: string, path: string, symbol?: string) => http.get<ImpactResult>(`/api/repos/${enc(id)}/impact`, { path, symbol }),
  repoSettings: (id: string, body: { autoReview?: boolean; autoFixCi?: boolean }) => http.patch<Repo>(`/api/repos/${enc(id)}/settings`, body),
  reviews: (id: string) => http.get<{ items: PrReview[] }>(`/api/repos/${enc(id)}/reviews`),
  reviewPr: (id: string, number: number, post: boolean) => http.post<PrReview>(`/api/repos/${enc(id)}/reviews`, { number, post }),
  ciRuns: (id: string) => http.get<{ items: CiItem[] }>(`/api/repos/${enc(id)}/ci`),
  ciFix: (id: string, runId: number) => http.post<{ taskId?: string; summary: string }>(`/api/repos/${enc(id)}/ci/${runId}/fix`),
  budget: () => http.get<BudgetStatus>('/api/budget'),
  setBudget: (budgetUsd: number | null) => http.put<BudgetStatus>('/api/budget', { budgetUsd }),
  mcpServers: () => http.get<{ items: McpServer[] }>('/api/mcp'),
  addMcp: (body: McpInput) => http.post<McpServer>('/api/mcp', body),
  toggleMcp: (id: string, enabled: boolean) => http.patch<McpServer>(`/api/mcp/${enc(id)}`, { enabled }),
  testMcp: (id: string) => http.post<McpServer>(`/api/mcp/${enc(id)}/test`),
  deleteMcp: (id: string) => http.del<void>(`/api/mcp/${enc(id)}`),
  notifications: () => http.get<NotifySettings>('/api/notifications'),
  setNotifications: (body: { slackUrl?: string | null; discordUrl?: string | null; events?: string[] }) => http.put<NotifySettings>('/api/notifications', body),
  testNotifications: () => http.post<{ slack?: boolean; discord?: boolean }>('/api/notifications/test'),
  llmCheck: () => http.get<LlmCheck>('/api/llm/check'),
  benchmark: () => http.get<BenchResult>('/api/eval/latest'),
  benchmarkStatus: () => http.get<BenchStatus>('/api/eval/status'),
  runBenchmark: (limit?: number) => http.post<BenchStatus>('/api/eval/run', limit ? { limit } : {}),
  me: () => http.get<Me>('/api/me'),
  connectGithub: (token: string) => http.post<{ login: string; avatarUrl: string }>('/api/github/connect', { token }),
  disconnectGithub: () => http.del<{ ok: true }>('/api/github/connect'),
  githubRepos: (query?: string) => http.get<{ items: GithubRepo[] }>('/api/github/repos', { query }),

  repos: () => http.get<{ items: Repo[] }>('/api/repos'),
  repo: (id: string) => http.get<Repo>(`/api/repos/${enc(id)}`),
  createRepo: (input: CreateRepoInput) => http.post<Repo>('/api/repos', input),
  deleteRepo: (id: string) => http.del<{ ok: true }>(`/api/repos/${enc(id)}`),
  reindexRepo: (id: string) => http.post<Repo>(`/api/repos/${enc(id)}/reindex`),
  tree: (id: string) => http.get<{ files: TreeFile[] }>(`/api/repos/${enc(id)}/tree`),
  file: (id: string, path: string) => http.get<FileContent>(`/api/repos/${enc(id)}/file`, { path }),
  graph: (id: string) => http.get<GraphData>(`/api/repos/${enc(id)}/graph`),
  health: (id: string) => http.get<HealthReport>(`/api/repos/${enc(id)}/health`),
  search: (id: string, query: string) => http.post<{ results: SearchResult[] }>(`/api/repos/${enc(id)}/search`, { query }),
  explain: (id: string, path: string, question?: string) =>
    http.post<{ explanation: string; usage: Usage }>(`/api/repos/${enc(id)}/explain`, { path, question }),
  bugs: (id: string, paths?: string[]) => http.post<{ findings: Finding[]; usage: Usage }>(`/api/repos/${enc(id)}/bugs`, { paths }),
  security: (id: string) => http.post<SecurityReport>(`/api/repos/${enc(id)}/security`),
  issues: (id: string) => http.get<{ items: RepoIssue[] }>(`/api/repos/${enc(id)}/issues`),
  runIssue: (id: string, number: number) => http.post<Task>(`/api/repos/${enc(id)}/issues/${number}/run`),
  memory: (id: string) => http.get<{ items: MemoryNote[] }>(`/api/repos/${enc(id)}/memory`),
  addMemory: (id: string, text: string) => http.post<MemoryNote>(`/api/repos/${enc(id)}/memory`, { text }),
  deleteMemory: (id: string, noteId: string) => http.del<{ ok: true }>(`/api/repos/${enc(id)}/memory/${enc(noteId)}`),
  chat: (id: string, message: string, threadId?: string) => http.post<ChatThread>(`/api/repos/${enc(id)}/chat`, { threadId, message }),
  chats: (id: string) => http.get<{ items: ChatSummary[] }>(`/api/repos/${enc(id)}/chats`),
  chatThread: (id: string, threadId: string) => http.get<ChatThread>(`/api/repos/${enc(id)}/chats/${enc(threadId)}`),

  createTask: (repoId: string, input: CreateTaskInput) => http.post<Task>(`/api/repos/${enc(repoId)}/tasks`, input),
  tasks: (params: { repoId?: string; status?: TaskStatus; limit?: number; cursor?: string }) => http.get<TaskPage>('/api/tasks', params),
  task: (id: string) => http.get<TaskDetail>(`/api/tasks/${enc(id)}`),
  cancelTask: (id: string) => http.post<Task>(`/api/tasks/${enc(id)}/cancel`),
  resolveApproval: (taskId: string, approvalId: string, decision: ApprovalDecision) =>
    http.post<{ task: Task; approval: ApprovalRecord }>(`/api/tasks/${enc(taskId)}/approvals/${enc(approvalId)}`, decision),
  taskDiff: (id: string) => http.get<TaskDiff>(`/api/tasks/${enc(id)}/diff`),
  createPr: (id: string, input: CreatePrInput) => http.post<{ task: Task; pr: NonNullable<Task['pr']> }>(`/api/tasks/${enc(id)}/pr`, input),

  activity: (limit = 60) => http.get<{ items: ActivityItem[] }>(`/api/activity?limit=${limit}`),
  stats: () => http.get<Stats>('/api/stats'),
  audit: (cursor?: string) => http.get<AuditPage>('/api/audit', { limit: 50, cursor }),
  apiHealth: () => http.get<ApiHealth>('/api/health'),
};
